// ─── Graph Data ───────────────────────────────────────────────────────────────

export function getGraphData(): GraphData {
  const nodes = [
    ...POLITICIANS.map((p) => ({
      id: p.id,
      type: "politician" as const,
      label: p.name,
      slug: p.slug,
      party: p.party,
      partyColor: p.partyColor,
      score: p.score,
    })),
    ...ENTITIES.map((e) => ({
      id: e.id,
      type: "entity" as const,
      label: e.name,
      entityType: e.type,
    })),
  ];

  const edges = RELATIONSHIPS.map((r) => ({
    id: r.id,
    source: r.politicianId,
    target: r.entityId,
    type: r.type,
    value: r.value,
    label: r.type.replace("_", " "),
  }));

  return { nodes, edges };
}

// ─── Stats ────────────────────────────────────────────────────────────────────

export function getStats(): Stats {
  const totalScore = POLITICIANS.reduce((acc, p) => acc + p.score, 0);
  const criticalCount = POLITICIANS.filter(
    (p) => p.maxSeverity === "critical"
  ).length;

  return {
    totalPoliticians: POLITICIANS.length,
    totalArticles: ARTICLES.length,
    totalEntities: ENTITIES.length,
    totalRelationships: RELATIONSHIPS.length,
    avgScore: Math.round(totalScore / POLITICIANS.length),
    criticalCount,
  };
}

