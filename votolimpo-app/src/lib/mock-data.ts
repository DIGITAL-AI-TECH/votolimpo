export function getRelationshipsForPolitician(politicianId: string): Relationship[] {
  return RELATIONSHIPS.filter((r) => r.politicianId === politicianId);
}

export function searchPoliticians(query: string): Politician[] {
  const q = query.toLowerCase();
  return POLITICIANS.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.party.toLowerCase().includes(q) ||
      p.uf.toLowerCase().includes(q) ||
      p.role.toLowerCase().includes(q)
  );
}

export function getPartiesList(): string[] {
  return [...new Set(POLITICIANS.map((p) => p.party))].sort();
}

export function getUFList(): string[] {
  return [...new Set(POLITICIANS.map((p) => p.uf))].sort();
}

export function getRanking(
  party?: string,
  uf?: string,
  page = 1,
  pageSize = 20,
  sortBy = "score",
  sortOrder: "asc" | "desc" = "asc"
): { data: Politician[]; total: number } {
  let filtered = [...POLITICIANS];

  if (party) filtered = filtered.filter((p) => p.party === party);
  if (uf) filtered = filtered.filter((p) => p.uf === uf);

  const severityWeight: Record<string, number> = {
    critical: 4,
    high: 3,
    medium: 2,
    low: 1,
    info: 0,
  };

  filtered.sort((a, b) => {
    let comparison = 0;
    switch (sortBy) {
      case "name":
        comparison = a.name.localeCompare(b.name);
        break;
      case "score":
        comparison = a.score - b.score;
        break;
      case "articleCount":
        comparison = a.articleCount - b.articleCount;
        break;
      case "maxSeverity":
        comparison =
          severityWeight[a.maxSeverity] - severityWeight[b.maxSeverity];
        break;
      case "party":
        comparison = a.party.localeCompare(b.party);
        break;
      case "uf":
        comparison = a.uf.localeCompare(b.uf);
        break;
    }
    return sortOrder === "desc" ? -comparison : comparison;
  });

  const total = filtered.length;
  const start = (page - 1) * pageSize;
  const data = filtered.slice(start, start + pageSize);

  return { data, total };
}
